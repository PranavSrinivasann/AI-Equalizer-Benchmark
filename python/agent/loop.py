"""Orchestration for the agent loop (the model proposals come from outside this script).

  loop.py setup                     evaluate the baseline and hand references
  loop.py prompt N                  write results/agent/round_NN/prompt.md for round N
  loop.py evaluate N                evaluate results/agent/round_NN/response.md, update state
  loop.py oneshot-prompt            build the exact-function single-attempt prompt
  loop.py oneshot-evaluate          evaluate results/agent/oneshot/response.md
  loop.py control NAME              evaluate results/agent/NAME/response.md (single-shot control)
  loop.py summary                   print the attempt table
"""

import json
import re
import sys
import textwrap
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[1]
sys.path[:0] = [str(HERE), str(ROOT / "python" / "rtl_gen"), str(ROOT / "python" / "channel")]

import evaluate as ev  # noqa: E402

AGENT = ROOT / "results" / "agent"
STATE = AGENT / "state.json"
MODEL = "claude-sonnet-5-5"
DATE = "2026-10-31"
BASELINE = ROOT / "rtl" / "dj" / "ffe5tap_dj_loss30_baseline.sv"
HAND = ROOT / "rtl" / "dj" / "ffe5tap_dj_loss30_hand.sv"


def load():
    return json.loads(STATE.read_text()) if STATE.exists() else {"attempts": []}


def save(state):
    STATE.write_text(json.dumps(state, indent=2) + "\n")


def extract(response):
    blocks = re.findall(r"```(?:systemverilog|verilog|sv)?\n(.*?)```", response, re.S)
    if not blocks:
        raise SystemExit("no code block in response")
    code = blocks[0]
    change = re.search(r"CHANGE SUMMARY:\s*(.*?)(?:\n\s*HYPOTHESIS:|\Z)", response, re.S)
    hyp = re.search(r"HYPOTHESIS:\s*(.*)", response)
    return code, (change.group(1).strip() if change else ""), (hyp.group(1).strip() if hyp else "")


def header(label):
    return (f"// Generated by Claude ({MODEL}, as configured for the session) on {DATE}: {label}.\n"
            f"// Not edited by hand.\n")


def attempt_row(a):
    if not a["valid"]:
        why = a.get("failed", "gate")
        return f"| {a['round']} | FAILED {why} | - | - | - | {a.get('note', '')} |"
    return (f"| {a['round']} | valid | {a['logic_cells']} | {a['fmax']:.1f} | {a['score']:.3f} | "
            f"{a.get('note', '')} |")


def history_table(state):
    rows = [attempt_row(a) for a in state["attempts"]]
    return ("| round | result | logic cells | Fmax MHz | score | your change summary |\n"
            "|---|---|---|---|---|---|\n" + "\n".join(rows))


def best(state):
    valid = [a for a in state["attempts"] if a["valid"]]
    return min(valid, key=lambda a: a["score"]) if valid else None


def prompt(n):
    state = load()
    task = (ROOT / "prompts/agent/loop_task.md").read_text()
    parts = [task]
    base_report = json.loads((AGENT / "arms/baseline/report.json").read_text())
    if n == 1:
        parts.append("## Round 1 of 8: starting design\n\nNo attempts yet. This is the starting design "
                     "(generic multipliers). Its results:\n\n```\n" + ev.feedback_text(base_report) +
                     "\n```\n\nStarting RTL:\n\n```systemverilog\n" + BASELINE.read_text() + "```\n")
    else:
        parts.append(f"## Round {n} of 8\n\n### All attempts so far\n\n" + history_table(state))
        b = best(state)
        last = state["attempts"][-1]
        if b:
            rep = json.loads((ROOT / b["report"]).read_text())
            parts.append(f"\n### Best valid design so far (round {b['round']})\n\n```\n{ev.feedback_text(rep)}\n```\n\n"
                         f"```systemverilog\n{(ROOT / b['rtl']).read_text()}```\n")
        else:
            parts.append("\nNo valid design yet. The starting design is below.\n\n```systemverilog\n"
                         + BASELINE.read_text() + "```\n")
        if not b or last["round"] != b["round"]:
            rep = json.loads((ROOT / last["report"]).read_text())
            parts.append(f"\n### Your most recent attempt (round {last['round']}), which was not the best\n\n"
                         f"```\n{ev.feedback_text(rep)}\n```\n\n```systemverilog\n{(ROOT / last['rtl']).read_text()}```\n")
    folder = AGENT / f"round_{n:02d}"
    folder.mkdir(parents=True, exist_ok=True)
    (folder / "prompt.md").write_text("\n".join(parts))
    print(folder / "prompt.md", len("\n".join(parts)), "chars")


def evaluate_round(n):
    folder = AGENT / f"round_{n:02d}"
    response = (folder / "response.md").read_text()
    code, change, hyp = extract(response)
    rtl = ROOT / "rtl" / "agent" / f"round_{n:02d}.sv"
    rtl.write_text(header(f"agent loop round {n}") + code)
    rep = ev.evaluate(rtl, folder)
    state = load()
    a = {"round": n, "rtl": str(rtl.relative_to(ROOT)), "report": str((folder / "report.json").relative_to(ROOT)),
         "valid": rep["valid"], "note": textwrap.shorten(" ".join(change.split()), 230, placeholder="..."), "hypothesis": hyp}
    if rep["valid"]:
        s = rep["synthesis"]
        a.update(logic_cells=s["logic_cells"], fmax=s["fmax_median_mhz"], score=rep["score"])
    else:
        a["failed"] = ("G1" if not rep["g1_build"]["pass"] else
                       "G2" if not rep["g2_directed"]["pass"] else "G3" if not rep["g3_link"]["pass"] else "synthesis")
    state["attempts"] = [x for x in state["attempts"] if x["round"] != n] + [a]
    state["attempts"].sort(key=lambda x: x["round"])
    save(state)
    (folder / "feedback.txt").write_text(ev.feedback_text(rep))
    print(ev.feedback_text(rep))


def oneshot_prompt():
    from build_prompts import build
    c = ev.coefficients()
    folder = AGENT / "oneshot"
    folder.mkdir(parents=True, exist_ok=True)
    (folder / "prompt.md").write_text(build("dj_loss30", c))
    print(folder / "prompt.md")


def oneshot_evaluate():
    folder = AGENT / "oneshot"
    response = (folder / "response.md").read_text()
    blocks = re.findall(r"```(?:systemverilog|verilog|sv)?\n(.*?)```", response, re.S)
    rtl = ROOT / "rtl" / "agent" / "oneshot.sv"
    rtl.write_text(header("single attempt with the exact-function prompt") + blocks[0])
    print(ev.feedback_text(ev.evaluate(rtl, folder)))


def summary():
    state = load()
    print(history_table(state))
    b = best(state)
    if b:
        print("best:", b["round"], b["logic_cells"], round(b["fmax"], 1), round(b["score"], 3))


def control_evaluate(name):
    """Single-shot samples of the round-1 loop prompt (same prompt, no feedback, no further rounds)."""
    folder = AGENT / name
    response = (folder / "response.md").read_text()
    code, _, _ = extract(response)
    rtl = ROOT / "rtl" / "agent" / f"{name}.sv"
    rtl.write_text(header("single attempt with the round-1 loop prompt (control)") + code)
    print(ev.feedback_text(ev.evaluate(rtl, folder)))


def main():
    cmd = sys.argv[1]
    if cmd == "setup":
        ev.ensure_directed_vectors()
        for name, path in (("baseline", BASELINE), ("hand", HAND)):
            print(name)
            print(ev.feedback_text(ev.evaluate(path, AGENT / "arms" / name)))
    elif cmd == "prompt":
        prompt(int(sys.argv[2]))
    elif cmd == "evaluate":
        evaluate_round(int(sys.argv[2]))
    elif cmd == "oneshot-prompt":
        oneshot_prompt()
    elif cmd == "oneshot-evaluate":
        oneshot_evaluate()
    elif cmd == "control":
        control_evaluate(sys.argv[2])
    elif cmd == "summary":
        summary()


if __name__ == "__main__":
    main()
